// Writes data/catalog/catalog-nutrition-v1.sql from catalog-nutrition-v1.json: one recipe_nutrition row per recipe,
// hashed against the recipe as it is in the database (title, ingredients, steps, servings), so the app shows it.
// Run in the app container: npx tsx script/catalog-nutrition.ts    (reads DATABASE_URL; writes only the .sql file)
// Load it with psql. A recipe whose text later changes no longer matches its hash and shows no nutrition.
import { readFileSync, writeFileSync } from "node:fs";
import { pool } from "../server/db";
import { nutritionFingerprint } from "../server/recipe-nutrition";
import { recipeNutritionSchema } from "../shared/recipe-nutrition";

const source = JSON.parse(readFileSync("data/catalog/catalog-nutrition-v1.json", "utf8"));
const ids = Object.keys(source.recipes);
const { rows } = await pool.query("SELECT id, title, ingredients, steps, servings FROM recipes WHERE id = ANY($1)", [ids]);
await pool.end();
if (rows.length !== ids.length) throw new Error(`Missing recipes: ${ids.filter(id => !rows.some(r => r.id === id)).join(", ")}`);

const analyzedAt = "2026-11-24T00:00:00.000Z";
const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const values = rows.sort((a, b) => a.id.localeCompare(b.id)).map(recipe => {
  const inputHash = nutritionFingerprint(recipe);
  const data = recipeNutritionSchema.parse({ version: 1, source: "ai-estimate", model: source.model, analyzedAt, inputHash, ...source.recipes[recipe.id] });
  return `(${quote(recipe.id)},${quote(inputHash)},${quote(JSON.stringify(data))}::jsonb,${quote(analyzedAt)})`;
});
writeFileSync("data/catalog/catalog-nutrition-v1.sql", `-- Nutrition estimates for the 23 catalog recipes. Generated by script/catalog-nutrition.ts from catalog-nutrition-v1.json.
-- Upserts by recipe id; safe to rerun.
BEGIN;
INSERT INTO recipe_nutrition (recipe_id,input_hash,data,analyzed_at) VALUES
${values.join(",\n")}
ON CONFLICT (recipe_id) DO UPDATE SET input_hash=EXCLUDED.input_hash, data=EXCLUDED.data, analyzed_at=EXCLUDED.analyzed_at;
COMMIT;
`);
console.log(`Wrote ${values.length} rows.`);

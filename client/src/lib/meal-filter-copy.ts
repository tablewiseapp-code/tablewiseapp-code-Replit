export type MealFilterCopyKey = keyof typeof copy.en;

export function mealFilterCopy(lang: Language, key: MealFilterCopyKey, values?: Record<string, string | number>) {
  let text = copy[lang][key];
  if (values) {
    Object.entries(values).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value));
    });
  }
  return text;
}

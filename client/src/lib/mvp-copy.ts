type MvpKey = keyof typeof copy.en;

export function useMvpCopy() {
  const { lang, dir } = useAppI18n();
  const t = (key: MvpKey, values?: Record<string, string | number>) => {
    let result = copy[lang][key];
    if (values) {
      Object.entries(values).forEach(([name, value]) => {
        result = result.replaceAll(`{${name}}`, String(value));
      });
    }
    return result;
  };
  return { lang, dir, t };
}
